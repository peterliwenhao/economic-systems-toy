#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const githubIndex = args.indexOf("--github");
const githubRepo = githubIndex >= 0 ? args[githubIndex + 1] : null;
const sampleMode = args.includes("--sample") || !githubRepo;

if (githubIndex >= 0 && !githubRepo) {
  fail("--github 后需要 OWNER/REPO。");
}

const readJson = async (relativePath) => JSON.parse(await readFile(resolve(root, relativePath), "utf8"));
const project = await readJson("project/project.json");
const history = await readJson("records/history.json");
const tasks = sampleMode ? await readJson("examples/tasks.json") : loadGithubTasks(githubRepo);

project.branch = gitValue(["rev-parse", "--abbrev-ref", "HEAD"], project.branch || "main");
project.commit = gitValue(["rev-parse", "--short", "HEAD"], sampleMode ? "模板示例" : "unknown");

const output = { project, tasks, history };
const target = resolve(root, "dist/data.js");
await writeFile(target, `/* Generated by scripts/build-dashboard-data.mjs. */\nwindow.COOP_DATA = ${JSON.stringify(output, null, 2)};\n`, "utf8");
console.log(`Dashboard data generated: ${tasks.length} tasks, ${history.length} history entries.`);

function loadGithubTasks(repo) {
  let raw;
  try {
    raw = execFileSync("gh", [
      "issue", "list", "--repo", repo, "--state", "all", "--limit", "200",
      "--json", "number,title,body,state,assignees,labels,url"
    ], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  } catch (error) {
    const detail = error.stderr?.toString().trim() || error.message;
    fail(`无法读取 GitHub Issues。请确认已安装并登录 gh，然后重试。\n${detail}`);
  }

  return JSON.parse(raw)
    .filter((issue) => /\[?T-\d+\]?/i.test(issue.title) || issue.labels.some((item) => item.name === "research-task"))
    .map(githubIssueToTask);
}

function githubIssueToTask(issue) {
  const id = issue.title.match(/T-\d+/i)?.[0].toUpperCase() || `T-${String(issue.number).padStart(3, "0")}`;
  const labelNames = issue.labels.map((item) => item.name.toLowerCase());
  const status = statusFromLabels(labelNames, issue.state);
  const priority = (labelNames.find((label) => label.startsWith("priority:")) || "priority:p2").split(":")[1].toUpperCase();
  const module = (labelNames.find((label) => label.startsWith("module:")) || "module:general").split(":").slice(1).join(":");
  const goal = section(issue.body, "Goal") || "详见 GitHub Issue。";
  const scope = listItems(section(issue.body, "Scope"));
  const acceptance = listItems(section(issue.body, "Acceptance"));
  const evidence = listItems(section(issue.body, "Evidence"));
  const dependenciesText = section(issue.body, "Dependencies");
  const dependsOn = [...new Set(dependenciesText.match(/T-\d+/gi)?.map((item) => item.toUpperCase()) || [])];
  const title = issue.title.replace(/^\s*\[?T-\d+\]?\s*[:：-]?\s*/i, "").trim() || issue.title;
  const slug = title.toLowerCase().replace(/[^a-z0-9\u4e00-\u9fff]+/g, "-").replace(/^-|-$/g, "").slice(0, 36) || "task";
  const risks = section(issue.body, "Risks and open questions");

  return {
    id,
    title,
    owner: issue.assignees.map((item) => item.login).join(", ") || "待认领",
    status,
    priority,
    module,
    blocked: status === "blocked",
    ...(status === "blocked" ? { blockReason: firstUsefulLine(risks) || "详见 GitHub Issue。" } : {}),
    dependsOn,
    branch: `task/${id}-${slug}`,
    goal: firstUsefulLine(goal),
    scope: scope.length ? scope : ["在 Issue 中补充 Scope"],
    acceptance: acceptance.length ? acceptance : ["在 Issue 中补充 Acceptance"],
    evidence: evidence.length ? evidence : ["在 Issue 中补充 Evidence"],
    issueUrl: issue.url
  };
}

function section(body = "", heading) {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = body.match(new RegExp(`(?:^|\\n)#{2,3}\\s+${escaped}\\s*\\n([\\s\\S]*?)(?=\\n#{2,3}\\s+|$)`, "i"));
  return match?.[1]?.trim() || "";
}

function listItems(value = "") {
  return value.split("\n")
    .map((line) => line.replace(/^\s*[-*]\s*(?:\[[ xX]\]\s*)?/, "").trim())
    .filter((line) => line && !line.startsWith("<!--"));
}

function firstUsefulLine(value = "") {
  return listItems(value)[0] || value.split("\n").map((line) => line.trim()).find(Boolean) || "";
}

function statusFromLabels(labels, issueState) {
  const mapping = new Map([
    ["status:proposed", "proposed"], ["status:ready", "ready"],
    ["status:in-progress", "in_progress"], ["status:review", "review"],
    ["status:blocked", "blocked"], ["status:done", "done"]
  ]);
  for (const [label, status] of mapping) {
    if (labels.includes(label)) return status;
  }
  return issueState === "CLOSED" ? "done" : "proposed";
}

function gitValue(commandArgs, fallback) {
  try {
    return execFileSync("git", commandArgs, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || fallback;
  } catch {
    return fallback;
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
